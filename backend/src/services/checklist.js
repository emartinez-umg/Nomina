export function checklist(alias = 'e') {
  return {
    contract: `NOT EXISTS(SELECT 1 FROM NOM_RELACION_LABORAL r WHERE r.EML_ID=${alias}.EML_ID AND r.RLA_ESTADO='ACTIVA')`,
    bank: `NOT EXISTS(SELECT 1 FROM NOM_CUENTA_BANCARIA_EMPLEADO b WHERE b.EML_ID=${alias}.EML_ID)`,
    identity: `NOT EXISTS(SELECT 1 FROM ERP_PERSONA_DOCUMENTO d WHERE d.PER_ID=${alias}.PER_ID)`,
    emergency: `NOT EXISTS(SELECT 1 FROM NOM_CONTACTO_EMERGENCIA c WHERE c.EML_ID=${alias}.EML_ID)`,
    contact: `NOT EXISTS(SELECT 1 FROM ERP_PERSONA_CORREO c WHERE c.PER_ID=${alias}.PER_ID) AND NOT EXISTS(SELECT 1 FROM ERP_PERSONA_TELEFONO p WHERE p.PER_ID=${alias}.PER_ID)`,
    address: `NOT EXISTS(SELECT 1 FROM ERP_PERSONA_DIRECCION d WHERE d.PER_ID=${alias}.PER_ID)`,
    schedule: `EXISTS(SELECT 1 FROM NOM_RELACION_LABORAL r WHERE r.EML_ID=${alias}.EML_ID AND r.RLA_ESTADO='ACTIVA' AND NOT EXISTS(SELECT 1 FROM NOM_RELACION_JORNADA j WHERE j.RLA_ID=r.RLA_ID))`,
    contractType: `EXISTS(SELECT 1 FROM NOM_RELACION_LABORAL r WHERE r.EML_ID=${alias}.EML_ID AND r.RLA_ESTADO='ACTIVA' AND r.TCT_ID IS NULL)`,
  };
}
