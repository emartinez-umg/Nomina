export async function installPending(c) {
  for (const sql of pendingDDL) {
    try {
      await c.execute(sql);
    } catch (e) {
      if (![955, 2260, 2261, 2275, 2264].includes(e.errorNum)) throw e;
    }
  }
  for (const [role, description] of [
    ['NOMINA_SISTEMA', 'Administrador del Sistema'],
    ['NOMINA_ADMIN', 'Administrador de Nómina'],
    ['NOMINA_COLABORADOR', 'Colaborador'],
  ])
    await c.execute(
      'MERGE INTO ERP_ROL r USING (SELECT :role AS name FROM DUAL) s ON(r.ROL_NOMBRE=s.name) WHEN NOT MATCHED THEN INSERT(ROL_NOMBRE,ROL_DESCRIPCION) VALUES(s.name,:description)',
      { role, description },
    );
  await c.commit();
  // Upgrade payment states and make the reference conditional on confirmation.
  const payChecks = await c.execute(
    "SELECT CONSTRAINT_NAME,SEARCH_CONDITION_VC FROM USER_CONSTRAINTS WHERE TABLE_NAME='NOM_RH_PAGO_LIQ' AND CONSTRAINT_TYPE='C'",
  );
  for (const row of payChecks.rows || []) {
    const name = row.CONSTRAINT_NAME ?? row[0],
      sql = String(row.SEARCH_CONDITION_VC ?? row[1]);
    if (
      sql.includes('RPL_ESTADO') &&
      sql.includes("'CONFIRMADA'") &&
      !sql.includes("'PENDIENTE'") &&
      name !== 'CK_RPL_REFERENCIA'
    ) {
      if (!/^[A-Z][A-Z0-9_$#]*$/.test(name)) throw new Error('Nombre de restricción inesperado.');
      await c.execute(`ALTER TABLE NOM_RH_PAGO_LIQ DROP CONSTRAINT ${name}`);
    }
  }
  try {
    await c.execute(
      "ALTER TABLE NOM_RH_PAGO_LIQ ADD CONSTRAINT CK_RPL_ESTADOS CHECK(RPL_ESTADO IN('PENDIENTE','CONFIRMADA','RECHAZADA','ANULADA'))",
    );
  } catch (e) {
    if (e.errorNum !== 2264) throw e;
  }
  const nullable = await c.execute(
    "SELECT NULLABLE FROM USER_TAB_COLUMNS WHERE TABLE_NAME='NOM_RH_PAGO_LIQ' AND COLUMN_NAME='RPL_REFERENCIA'",
  );
  if ((nullable.rows[0]?.NULLABLE ?? nullable.rows[0]?.[0]) === 'N')
    await c.execute('ALTER TABLE NOM_RH_PAGO_LIQ MODIFY RPL_REFERENCIA NULL');
  try {
    await c.execute(
      "ALTER TABLE NOM_RH_PAGO_LIQ ADD CONSTRAINT CK_RPL_REFERENCIA CHECK(RPL_ESTADO<>'CONFIRMADA' OR TRIM(RPL_REFERENCIA) IS NOT NULL)",
    );
  } catch (e) {
    if (e.errorNum !== 2264) throw e;
  }
  // Add the new state without a window in which period states are unconstrained.
  const r = await c.execute(
    "SELECT SEARCH_CONDITION_VC FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME='CK_NPE_ESTADO'",
  );
  const condition = r.rows?.[0]?.SEARCH_CONDITION_VC ?? r.rows?.[0]?.[0] ?? '';
  if (!String(condition).includes('ANULADO')) {
    try {
      await c.execute(
        "ALTER TABLE NOM_PERIODO ADD CONSTRAINT CK_NPE_ESTADO_V2 CHECK (NPE_ESTADO IN ('ABIERTO','CALCULADO','PAGADO','CERRADO','ANULADO'))",
      );
    } catch (e) {
      if (e.errorNum !== 2264) throw e;
    }
    try {
      await c.execute('ALTER TABLE NOM_PERIODO DROP CONSTRAINT CK_NPE_ESTADO');
    } catch (e) {
      if (e.errorNum !== 2443) throw e;
    }
    await c.execute('ALTER TABLE NOM_PERIODO RENAME CONSTRAINT CK_NPE_ESTADO_V2 TO CK_NPE_ESTADO');
  }
}
