export function fieldLabel(name) {
  if (aliases[name]) return aliases[name];
  let v = name
    .split('_')
    .slice(1)
    .map((w) => accents[w] || w.toLowerCase())
    .join(' ');
  return v.charAt(0).toUpperCase() + v.slice(1);
}
