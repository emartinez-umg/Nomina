CREATE TABLE NOM_RELACION_LABORAL (
    RLA_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EML_ID NUMBER NOT NULL,
    PUE_ID NUMBER NOT NULL,
    SUC_ID NUMBER NOT NULL,
    DPT_ID NUMBER,
    TCT_ID NUMBER, -- 🆕 tipo de contrato (RF-01)
    RLA_FECHA_INGRESO DATE NOT NULL,
    RLA_FECHA_BAJA DATE,
    RLA_SALARIO NUMBER(18,2) NOT NULL,
    RLA_MOTIVO_BAJA VARCHAR2(300),
    MBA_ID NUMBER,
    RLA_ESTADO VARCHAR2(15) NOT NULL,
    USU_ID_CREA NUMBER NOT NULL,
    RLA_FECHA_CREA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOM_RELACION_LABORAL PRIMARY KEY (RLA_ID),
    CONSTRAINT FK_NOM_RLA_EML FOREIGN KEY (EML_ID) REFERENCES NOM_EMPLEADO (EML_ID),
    CONSTRAINT FK_NOM_RLA_PUE FOREIGN KEY (PUE_ID) REFERENCES NOM_PUESTO (PUE_ID),
    CONSTRAINT FK_NOM_RLA_SUC FOREIGN KEY (SUC_ID) REFERENCES ERP_SUCURSAL (SUC_ID),
    CONSTRAINT FK_NOM_RLA_DPT FOREIGN KEY (DPT_ID) REFERENCES ERP_DEPARTAMENTO (DPT_ID),
    CONSTRAINT FK_NOM_RLA_TCT FOREIGN KEY (TCT_ID) REFERENCES NOM_TIPO_CONTRATO (TCT_ID), -- 🆕
    CONSTRAINT FK_NOM_RLA_MBA FOREIGN KEY (MBA_ID) REFERENCES NOM_MOTIVO_BAJA (MBA_ID),
    CONSTRAINT FK_NOM_RLA_USU_CREA FOREIGN KEY (USU_ID_CREA) REFERENCES ERP_USUARIO (USU_ID),
    CONSTRAINT CK_NOM_RLA_FECHAS CHECK (RLA_FECHA_BAJA IS NULL OR RLA_FECHA_BAJA >= RLA_FECHA_INGRESO),
    CONSTRAINT CK_NOM_RLA_SALARIO CHECK (RLA_SALARIO > 0),
    CONSTRAINT CK_NOM_RLA_ESTADO CHECK (RLA_ESTADO IN ('ACTIVA','FINALIZADA','SUSPENDIDA'))
