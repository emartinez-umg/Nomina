CREATE UNIQUE INDEX UX_NOM_NPE_ABIERTO ON NOM_PERIODO (
    CASE WHEN NPE_ESTADO = 'ABIERTO' THEN EMP_ID END,
    CASE WHEN NPE_ESTADO = 'ABIERTO' THEN NPE_TIPO END
);

