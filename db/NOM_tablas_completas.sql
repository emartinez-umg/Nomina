CREATE TABLE NOM_EMPLEADO (
    EML_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PER_ID NUMBER NOT NULL,
    EMP_ID NUMBER NOT NULL,
    SUC_ID NUMBER NOT NULL,
    DPT_ID NUMBER,
    PUE_ID NUMBER NOT NULL,
    EML_CODIGO VARCHAR2(20) NOT NULL,
    EML_FECHA_INGRESO DATE NOT NULL,
    EML_SALARIO NUMBER(18,2) NOT NULL,
    EML_IGSS VARCHAR2(30),
    EML_ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_NOM_EMPLEADO PRIMARY KEY (EML_ID),
    CONSTRAINT UQ_NOM_EMPLEADO UNIQUE (EMP_ID, EML_CODIGO),
    CONSTRAINT UQ_NOM_EML_EMP_PER UNIQUE (EMP_ID, PER_ID),
    CONSTRAINT FK_EML_PER FOREIGN KEY (PER_ID) REFERENCES ERP_PERSONA (PER_ID),
