CREATE TABLE NOM_PERIODO (
    NPE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EMP_ID NUMBER NOT NULL,
    NPE_FECHA_INICIO DATE NOT NULL,
    NPE_FECHA_FIN DATE NOT NULL,
    NPE_TIPO VARCHAR2(15) NOT NULL,
    NPE_ESTADO VARCHAR2(15) NOT NULL,
    NPE_QUINCENA NUMBER(1),
    CONSTRAINT PK_NOM_PERIODO PRIMARY KEY (NPE_ID),
    CONSTRAINT UQ_NOM_PERIODO UNIQUE (EMP_ID, NPE_FECHA_INICIO, NPE_FECHA_FIN),
