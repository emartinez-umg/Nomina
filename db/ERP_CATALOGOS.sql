MERGE INTO CXP_TIPO_DOCUMENTO d
USING (SELECT 'FACTURA' nombre, 'FACT' codigo FROM dual UNION ALL SELECT 'NOTA DE CREDITO', 'NCRE' FROM dual UNION ALL SELECT 'NOTA DE DEBITO', 'NDEB' FROM dual UNION ALL SELECT 'FACTURA ESPECIAL', 'FESP' FROM dual) s
ON (d.TDO_NOMBRE = s.nombre)
WHEN NOT MATCHED THEN INSERT (TDO_NOMBRE, TDO_CODIGO_SAT, TDO_GENERA_CXP) VALUES (s.nombre, s.codigo, 1);

