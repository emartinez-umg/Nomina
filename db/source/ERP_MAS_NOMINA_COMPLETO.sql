       SELECT 1
         FROM CON_PERIODO_CONTABLE PC
        WHERE PC.EFI_ID = P.EFI_ID
          AND P.PAR_FECHA BETWEEN PC.PCO_FECHA_INICIO AND PC.PCO_FECHA_FIN
   );

