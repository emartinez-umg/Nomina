USING (SELECT 'FACTURA' nombre, 'FACT' codigo FROM dual UNION ALL SELECT 'NOTA DE CREDITO', 'NCRE' FROM dual UNION ALL SELECT 'NOTA DE DEBITO', 'NDEB' FROM dual UNION ALL SELECT 'FACTURA ESPECIAL', 'FESP' FROM dual) s
ON (d.TDO_NOMBRE = s.nombre)
WHEN NOT MATCHED THEN INSERT (TDO_NOMBRE, TDO_CODIGO_SAT, TDO_GENERA_CXP) VALUES (s.nombre, s.codigo, 1);

MERGE INTO CXP_TIPO_NOTA d
USING (SELECT 'NOTA DE CREDITO' nombre, -1 signo FROM dual UNION ALL SELECT 'NOTA DE DEBITO', 1 FROM dual) s
ON (d.TNO_NOMBRE = s.nombre)
WHEN NOT MATCHED THEN INSERT (TNO_NOMBRE, TNO_SIGNO) VALUES (s.nombre, s.signo);

MERGE INTO CXP_ESTADO_NOTA d
USING (SELECT 'BORRADOR' nombre FROM dual UNION ALL SELECT 'REGISTRADA' FROM dual UNION ALL SELECT 'APLICADA' FROM dual UNION ALL SELECT 'ANULADA' FROM dual) s
ON (d.ENO_NOMBRE = s.nombre)
WHEN NOT MATCHED THEN INSERT (ENO_NOMBRE) VALUES (s.nombre);

MERGE INTO CXP_TIPO_RETENCION d
USING (SELECT 'IVA' nombre FROM dual UNION ALL SELECT 'ISR' FROM dual) s
ON (d.TRT_NOMBRE = s.nombre)
WHEN NOT MATCHED THEN INSERT (TRT_NOMBRE) VALUES (s.nombre);

