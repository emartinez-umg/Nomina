import oracledb from 'oracledb';
export async function inspectSchema(c) {
  const rows = async (sql) =>
    (await c.execute(sql, {}, { outFormat: oracledb.OUT_FORMAT_OBJECT })).rows;
  const tables = await rows('SELECT TABLE_NAME FROM USER_TABLES ORDER BY TABLE_NAME');
  const columns = await rows(
    'SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,DATA_PRECISION,DATA_SCALE,DATA_LENGTH,CHAR_USED,NULLABLE,DATA_DEFAULT,IDENTITY_COLUMN,COLUMN_ID FROM USER_TAB_COLUMNS ORDER BY TABLE_NAME,COLUMN_ID',
  );
  const constraints = await rows(
    "SELECT C.TABLE_NAME,C.CONSTRAINT_NAME,C.CONSTRAINT_TYPE,C.SEARCH_CONDITION_VC,C.INDEX_NAME,C.DELETE_RULE,R.TABLE_NAME REF_TABLE,R.CONSTRAINT_NAME REF_CONSTRAINT FROM USER_CONSTRAINTS C LEFT JOIN USER_CONSTRAINTS R ON R.CONSTRAINT_NAME=C.R_CONSTRAINT_NAME WHERE C.GENERATED='USER NAME' ORDER BY C.CONSTRAINT_NAME",
  );
  const cc = await rows(
    'SELECT CONSTRAINT_NAME,COLUMN_NAME,POSITION FROM USER_CONS_COLUMNS ORDER BY CONSTRAINT_NAME,POSITION',
  );
  const indexes = await rows(
    "SELECT INDEX_NAME,TABLE_NAME,UNIQUENESS FROM USER_INDEXES WHERE INDEX_TYPE NOT LIKE 'LOB%' ORDER BY INDEX_NAME",
  );
  const ic = await rows(
    'SELECT INDEX_NAME,COLUMN_NAME,COLUMN_POSITION FROM USER_IND_COLUMNS ORDER BY INDEX_NAME,COLUMN_POSITION',
  );
  const ie = await rows(
    'SELECT INDEX_NAME,COLUMN_POSITION,COLUMN_EXPRESSION FROM USER_IND_EXPRESSIONS',
  );
  const constraintIndexes = new Set(constraints.map((c) => c.INDEX_NAME).filter(Boolean));
  return tables.map((t) => ({
    name: t.TABLE_NAME,
    columns: columns
      .filter((c) => c.TABLE_NAME === t.TABLE_NAME)
      .map((c) => ({
        name: c.COLUMN_NAME,
        type: c.DATA_TYPE.startsWith('TIMESTAMP') ? 'TIMESTAMP' : c.DATA_TYPE,
        precision: c.DATA_PRECISION,
        scale: c.DATA_SCALE,
        length: c.DATA_LENGTH,
        charUsed: c.CHAR_USED,
        required: c.NULLABLE === 'N',
        identity: c.IDENTITY_COLUMN === 'YES',
        default: c.IDENTITY_COLUMN === 'YES' ? null : c.DATA_DEFAULT?.trim() || null,
      })),
    constraints: constraints
      .filter((c) => c.TABLE_NAME === t.TABLE_NAME)
      .map((c) => ({
        name: c.CONSTRAINT_NAME,
        type: c.CONSTRAINT_TYPE,
        columns: cc
          .filter((x) => x.CONSTRAINT_NAME === c.CONSTRAINT_NAME)
          .map((x) => x.COLUMN_NAME),
        ...(c.CONSTRAINT_TYPE === 'C' ? { sql: c.SEARCH_CONDITION_VC } : {}),
        ...(c.REF_TABLE
          ? {
              ref: {
                table: c.REF_TABLE,
                columns: cc
                  .filter((x) => x.CONSTRAINT_NAME === c.REF_CONSTRAINT)
                  .map((x) => x.COLUMN_NAME),
              },
              deleteRule: c.DELETE_RULE,
            }
          : {}),
      })),
    indexes: indexes
      .filter((x) => x.TABLE_NAME === t.TABLE_NAME && !constraintIndexes.has(x.INDEX_NAME))
      .map((x) => ({
        name: x.INDEX_NAME,
        unique: x.UNIQUENESS === 'UNIQUE',
        expressions: ic
          .filter((y) => y.INDEX_NAME === x.INDEX_NAME)
          .map(
            (y) =>
              ie.find(
                (z) => z.INDEX_NAME === x.INDEX_NAME && z.COLUMN_POSITION === y.COLUMN_POSITION,
              )?.COLUMN_EXPRESSION || y.COLUMN_NAME,
          ),
      })),
  }));
}
export function schemaDdl(tables) {
  const type = (f) =>
    f.type === 'NUMBER'
      ? `NUMBER${f.precision !== null ? `(${f.precision}${f.scale ? ', ' + f.scale : ''})` : ''}`
      : ['VARCHAR2', 'CHAR'].includes(f.type)
        ? `${f.type}(${f.length}${f.charUsed === 'C' ? ' CHAR' : ' BYTE'})`
        : f.type;
  const creates = tables.map(
    (t) =>
      `CREATE TABLE ${t.name} (\n${t.columns.map((f) => `    ${f.name} ${type(f)}${f.identity ? ' GENERATED BY DEFAULT AS IDENTITY' : f.default ? ' DEFAULT ' + f.default : ''}${f.required ? ' NOT NULL' : ''}`).join(',\n')}\n);`,
  );
  const constraints = [];
  for (const kind of ['P', 'U', 'C', 'R'])
    for (const t of tables)
      for (const c of t.constraints.filter((c) => c.type === kind))
        constraints.push(
          `ALTER TABLE ${t.name} ADD CONSTRAINT ${c.name} ${kind === 'P' ? 'PRIMARY KEY (' + c.columns.join(', ') + ')' : kind === 'U' ? 'UNIQUE (' + c.columns.join(', ') + ')' : kind === 'C' ? 'CHECK (' + c.sql + ')' : 'FOREIGN KEY (' + c.columns.join(', ') + ') REFERENCES ' + c.ref.table + ' (' + c.ref.columns.join(', ') + ')' + (c.deleteRule === 'CASCADE' ? ' ON DELETE CASCADE' : c.deleteRule === 'SET NULL' ? ' ON DELETE SET NULL' : '')};`,
        );
  const indexes = tables.flatMap((t) =>
    t.indexes.map(
      (i) =>
        `CREATE ${i.unique ? 'UNIQUE ' : ''}INDEX ${i.name} ON ${t.name} (${i.expressions.join(', ')});`,
    ),
  );
  return (
    '-- Esquema final consolidado para instalaciones NUEVAS.\n-- Generado desde el diccionario de Oracle; no ejecutar sobre un esquema poblado.\n\n' +
    [...creates, ...constraints, ...indexes].join('\n\n') +
    '\n'
  );
}
