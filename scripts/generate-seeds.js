import { writeFileSync, readFileSync } from 'node:fs';
import { demoData } from './lib/demo-data.js';
import { targetModel } from './lib/migration-data.js';
import { parseScript } from './lib/sql-script.js';
const data = demoData(),
  names = new Set(
    Object.entries(data)
      .filter(([, r]) => r.length)
      .map(([n]) => n),
  ),
  sql = [
    '-- Datos FICTICIOS para una instalación local nueva. No usar como información fiscal real.',
  ];
const quote = (value) => "'" + String(value).replaceAll("'", "''") + "'";
while (names.size) {
  let progress = false;
  for (const name of [...names]) {
    const table = targetModel.find((t) => t.name === name);
    if (
      table.constraints.some(
        (c) => c.type === 'R' && c.ref.table !== name && names.has(c.ref.table),
      )
    )
      continue;
    for (const row of data[name]) {
      const fields = table.columns.filter((f) => Object.hasOwn(row, f.name));
      const values = fields.map((f) => {
        const v = row[f.name];
        if (v === null) return 'NULL';
        if (f.type === 'NUMBER') {
          if (!/^-?\d+(\.\d+)?$/.test(v)) throw Error('Not a decimal');
          return v;
        }
        if (f.type === 'DATE')
          return `TO_DATE(${quote(v)},'${v.includes('T') ? 'YYYY-MM-DD"T"HH24:MI:SS' : 'YYYY-MM-DD'}')`;
        if (f.type === 'TIMESTAMP')
          return `TO_TIMESTAMP(${quote(v)},'YYYY-MM-DD"T"HH24:MI:SS.FF6')`;
        return quote(v);
      });
      sql.push(
        `INSERT INTO ${name} (${fields.map((f) => f.name).join(', ')}) VALUES (${values.join(', ')});`,
      );
    }
    const identity = table.columns.find((c) => c.identity);
    if (identity)
      sql.push(
        `ALTER TABLE ${name} MODIFY (${identity.name} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE));`,
      );
    names.delete(name);
    progress = true;
  }
  if (!progress) throw Error('Cycle');
}
sql.push('COMMIT;');
writeFileSync('db/seed.sql', sql.join('\n') + '\n');
const catalogStatements = parseScript(readFileSync('db/ERP_MAS_NOMINA_CORREGIDO.sql', 'utf8'))
  .filter((s) => s.sql.startsWith('MERGE'))
  .map(
    (s) =>
      s.sql.replaceAll('NOM_TIPO_COMISION', 'NOM_TIPO_INGRESO').replaceAll('TCO_', 'TIN_') + ';',
  );
for (const [code, name, value] of [
  ['FACTOR_HORA_EXTRA', 'Factor de hora extra ordinaria', 1.5],
  ['BONIFICACION_EXENTA_ISR_IGSS', 'Bonificacion decreto exenta de ISR e IGSS', 1],
])
  catalogStatements.push(
    `MERGE INTO NOM_PARAMETRO_LABORAL d USING (SELECT EMP_ID FROM ERP_EMPRESA) s ON (d.EMP_ID=s.EMP_ID AND d.NPL_CODIGO='${code}' AND d.NPL_FECHA_DESDE=DATE '2026-01-01') WHEN NOT MATCHED THEN INSERT (EMP_ID,NPL_CODIGO,NPL_NOMBRE,NPL_VALOR,NPL_FECHA_DESDE) VALUES (s.EMP_ID,'${code}','${name}',${value},DATE '2026-01-01');`,
  );
writeFileSync(
  'db/ERP_CATALOGOS.sql',
  '-- Catálogos idempotentes del script y parámetros por empresa, después de cargar empresas.\n\n' +
    catalogStatements.join('\n\n') +
    '\nCOMMIT;\n',
);
console.log('Semillas del ERP generadas; todos los datos de ejemplo son ficticios.');
